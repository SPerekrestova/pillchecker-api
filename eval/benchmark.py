"""NER benchmark — measures PharmaDetect accuracy on packaging text.

Runs the full pipeline (OCR cleaner → NER) and optionally the RxNorm
validation step. Produces precision/recall/F1 by category and overall.

Dataset is generated by prepare_hf_dataset.py from the HuggingFace
MattBastar/Medicine_Details dataset (11.8K medicines with compositions).

Usage:
    uv run python eval/benchmark.py                  # full dataset
    uv run python eval/benchmark.py --limit 500      # quick run
    uv run python eval/benchmark.py --with-rxnorm    # full pipeline (needs network)
"""

import argparse
import asyncio
import json
import sys
import time
from dataclasses import dataclass, field
from pathlib import Path

# Add project root to path
sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from app.nlp import ner_model
from app.nlp.ocr_cleaner import clean as ocr_clean

DATASET_PATH = Path(__file__).parent / "hf_medicine_dataset.json"
DRUG_LABELS = {"CHEM", "Chemical", "CHEMICAL"}


@dataclass
class CaseResult:
    case_id: str
    category: str
    text: str
    expected: list[str]
    ner_found: list[str]
    pipeline_found: list[str] = field(default_factory=list)
    ner_tp: int = 0
    ner_fp: int = 0
    ner_fn: int = 0
    pipeline_tp: int = 0
    pipeline_fp: int = 0
    pipeline_fn: int = 0
    ner_time_ms: float = 0.0
    pipeline_time_ms: float = 0.0


def normalize(name: str) -> str:
    """Normalize drug name for comparison."""
    return name.lower().strip()


def score(found: list[str], expected: list[str]) -> tuple[int, int, int]:
    """Calculate TP, FP, FN between found and expected drug lists."""
    found_norm = {normalize(f) for f in found}
    expected_norm = {normalize(e) for e in expected}

    # Exact match only
    tp = 0
    matched_expected = set()
    matched_found = set()

    for exp in expected_norm:
        for fnd in found_norm:
            if fnd in matched_found:
                continue
            if exp == fnd:
                tp += 1
                matched_expected.add(exp)
                matched_found.add(fnd)
                break

    fp = len(found_norm - matched_found)
    fn = len(expected_norm - matched_expected)
    return tp, fp, fn


def run_ner(text: str) -> tuple[list[str], float]:
    """Run OCR cleaner + NER, return drug names and time in ms."""
    cleaned = ocr_clean(text)
    start = time.perf_counter()
    entities = ner_model.predict(cleaned)
    elapsed_ms = (time.perf_counter() - start) * 1000

    drug_names = []
    seen = set()
    for e in entities:
        if e.label not in DRUG_LABELS or e.text.isdigit() or len(e.text.strip()) <= 1:
            continue
        name = e.text.strip()
        if name.lower() not in seen:
            seen.add(name.lower())
            drug_names.append(name)

    return drug_names, elapsed_ms


async def run_pipeline(text: str) -> tuple[list[str], float]:
    """Run full pipeline (NER + RxNorm validation), return drug names and time."""
    from app.services.drug_analyzer import analyze

    start = time.perf_counter()
    results = await analyze(text)
    elapsed_ms = (time.perf_counter() - start) * 1000

    names = [r["name"] for r in results]
    return names, elapsed_ms


def print_table(rows: list[list[str]], header: list[str]) -> None:
    """Print a formatted ASCII table."""
    all_rows = [header] + rows
    widths = [max(len(str(cell)) for cell in col) for col in zip(*all_rows)]

    def fmt(row):
        return " | ".join(str(cell).ljust(w) for cell, w in zip(row, widths))

    print(fmt(header))
    print("-+-".join("-" * w for w in widths))
    for row in rows:
        print(fmt(row))


def calc_metrics(tp: int, fp: int, fn: int) -> tuple[float, float, float]:
    """Calculate precision, recall, F1."""
    precision = tp / (tp + fp) if (tp + fp) > 0 else 1.0
    recall = tp / (tp + fn) if (tp + fn) > 0 else 1.0
    f1 = 2 * precision * recall / (precision + recall) if (precision + recall) > 0 else 0.0
    return precision, recall, f1


def get_text(case: dict) -> str:
    """Get input text from a case, handling both field naming conventions."""
    return case.get("ocr_text") or case.get("text", "")


def get_expected(case: dict) -> list[str]:
    """Get expected drug names from a case, handling both field naming conventions."""
    return case.get("expected_names") or case.get("expected_drugs", [])


def main():
    parser = argparse.ArgumentParser(description="NER benchmark for PharmaDetect")
    parser.add_argument("--limit", type=int, default=0,
                        help="Max cases to evaluate (0 = all)")
    parser.add_argument("--with-rxnorm", action="store_true",
                        help="Also run full pipeline with RxNorm validation")
    parser.add_argument("--verbose", "-v", action="store_true",
                        help="Show per-case details")
    args = parser.parse_args()

    # Load dataset
    if not DATASET_PATH.exists():
        print(f"Dataset not found: {DATASET_PATH}")
        print("Run 'uv run python eval/prepare_hf_dataset.py' to generate the dataset.")
        sys.exit(1)

    dataset = json.loads(DATASET_PATH.read_text())
    if args.limit > 0:
        dataset = dataset[:args.limit]
    print(f"Loaded {len(dataset)} test cases from {DATASET_PATH.name}")

    # Load model
    print("Loading NER model...")
    t0 = time.perf_counter()
    ner_model.load_model()
    load_time = time.perf_counter() - t0
    print(f"Model loaded in {load_time:.1f}s")
    print()

    # Run evaluation
    results: list[CaseResult] = []

    for case in dataset:
        ocr_text = get_text(case)
        expected_names = get_expected(case)
        ner_found, ner_ms = run_ner(ocr_text)
        tp, fp, fn = score(ner_found, expected_names)

        cr = CaseResult(
            case_id=case["id"],
            category=case.get("category", "real_world"),
            text=ocr_text,
            expected=expected_names,
            ner_found=ner_found,
            ner_tp=tp,
            ner_fp=fp,
            ner_fn=fn,
            ner_time_ms=ner_ms,
        )

        if args.with_rxnorm:
            pipeline_found, pipeline_ms = asyncio.run(run_pipeline(ocr_text))
            ptp, pfp, pfn = score(pipeline_found, expected_names)
            cr.pipeline_found = pipeline_found
            cr.pipeline_tp = ptp
            cr.pipeline_fp = pfp
            cr.pipeline_fn = pfn
            cr.pipeline_time_ms = pipeline_ms

        results.append(cr)

    # === Report: Per-case details ===

    if args.verbose:
        print("=" * 70)
        print("PER-CASE RESULTS (NER only)")
        print("=" * 70)
        for r in results:
            status = "PASS" if r.ner_fn == 0 and r.ner_fp == 0 else "FAIL"
            print(f"\n[{status}] {r.case_id} ({r.category})")
            print(f"  Input:    {r.text[:80]}{'...' if len(r.text) > 80 else ''}")
            print(f"  Expected: {r.expected}")
            print(f"  Found:    {r.ner_found}")
            if r.ner_fn > 0:
                missed = set(normalize(e) for e in r.expected) - set(normalize(f) for f in r.ner_found)
                print(f"  MISSED:   {missed}")
            if r.ner_fp > 0:
                extra = set(normalize(f) for f in r.ner_found) - set(normalize(e) for e in r.expected)
                print(f"  EXTRA:    {extra}")
            print(f"  Time:     {r.ner_time_ms:.0f}ms")
        print()

    # === Report: By category ===

    print("=" * 70)
    print("NER ACCURACY BY CATEGORY")
    print("=" * 70)

    categories = {}
    for r in results:
        cat = r.category
        if cat not in categories:
            categories[cat] = {"tp": 0, "fp": 0, "fn": 0, "count": 0, "time_ms": 0.0}
        categories[cat]["tp"] += r.ner_tp
        categories[cat]["fp"] += r.ner_fp
        categories[cat]["fn"] += r.ner_fn
        categories[cat]["count"] += 1
        categories[cat]["time_ms"] += r.ner_time_ms

    rows = []
    for cat, m in sorted(categories.items()):
        p, r_val, f1 = calc_metrics(m["tp"], m["fp"], m["fn"])
        avg_ms = m["time_ms"] / m["count"]
        rows.append([cat, str(m["count"]), f"{p:.0%}", f"{r_val:.0%}", f"{f1:.0%}",
                      f"{m['tp']}", f"{m['fp']}", f"{m['fn']}", f"{avg_ms:.0f}ms"])

    print_table(rows, ["Category", "N", "Prec", "Recall", "F1", "TP", "FP", "FN", "Avg ms"])

    # === Report: Overall ===

    print()
    total_tp = sum(r.ner_tp for r in results)
    total_fp = sum(r.ner_fp for r in results)
    total_fn = sum(r.ner_fn for r in results)
    p, r_val, f1 = calc_metrics(total_tp, total_fp, total_fn)
    avg_ms = sum(r.ner_time_ms for r in results) / len(results)

    print(f"OVERALL NER:  Precision={p:.1%}  Recall={r_val:.1%}  F1={f1:.1%}")
    print(f"              TP={total_tp}  FP={total_fp}  FN={total_fn}")
    print(f"              Avg inference: {avg_ms:.0f}ms/case")

    # === Detection rate (NER found any entity, regardless of name match) ===

    detected = sum(1 for r in results if r.ner_found)
    has_expected = sum(1 for r in results if r.expected)
    detected_with_expected = sum(1 for r in results if r.ner_found and r.expected)
    print(f"\nDETECTION: {detected}/{len(results)} cases had NER entities "
          f"({detected * 100 / len(results):.0f}%)")
    if has_expected:
        print(f"           {detected_with_expected}/{has_expected} cases with expected drugs "
              f"were detected ({detected_with_expected * 100 / has_expected:.0f}%)")

    # === Failures summary ===

    failures = [r for r in results if r.ner_fn > 0 or r.ner_fp > 0]
    if failures and args.verbose:
        print(f"\n{'=' * 70}")
        print(f"FAILURES ({len(failures)}/{len(results)} cases)")
        print(f"{'=' * 70}")
        for r in failures:
            issues = []
            if r.ner_fn > 0:
                missed = set(normalize(e) for e in r.expected) - set(normalize(f) for f in r.ner_found)
                issues.append(f"missed={missed}")
            if r.ner_fp > 0:
                extra = set(normalize(f) for f in r.ner_found) - set(normalize(e) for e in r.expected)
                issues.append(f"extra={extra}")
            print(f"  {r.case_id}: {', '.join(issues)}")
            print(f"    text: {r.text[:70]}...")
    elif failures:
        print(f"\nFAILURES: {len(failures)}/{len(results)} cases (use -v for details)")

    # === Pipeline results (if --with-rxnorm) ===

    if args.with_rxnorm:
        print(f"\n{'=' * 70}")
        print("FULL PIPELINE (NER + RxNorm validation)")
        print(f"{'=' * 70}")

        ptotal_tp = sum(r.pipeline_tp for r in results)
        ptotal_fp = sum(r.pipeline_fp for r in results)
        ptotal_fn = sum(r.pipeline_fn for r in results)
        pp, pr, pf1 = calc_metrics(ptotal_tp, ptotal_fp, ptotal_fn)
        pavg_ms = sum(r.pipeline_time_ms for r in results) / len(results)

        print(f"OVERALL PIPELINE:  Precision={pp:.1%}  Recall={pr:.1%}  F1={pf1:.1%}")
        print(f"                   TP={ptotal_tp}  FP={ptotal_fp}  FN={ptotal_fn}")
        print(f"                   Avg inference: {pavg_ms:.0f}ms/case")

        # NER found but RxNorm rejected
        ner_only = []
        for r in results:
            ner_set = set(normalize(n) for n in r.ner_found)
            pipe_set = set(normalize(n) for n in r.pipeline_found)
            rejected = ner_set - pipe_set
            if rejected:
                ner_only.append((r.case_id, rejected))

        if ner_only:
            print(f"\nNER found but RxNorm rejected ({len(ner_only)} cases):")
            for case_id, rejected in ner_only:
                print(f"  {case_id}: {rejected}")

        # RxNorm fallback caught (not in NER but in pipeline)
        fallback = []
        for r in results:
            ner_set = set(normalize(n) for n in r.ner_found)
            pipe_set = set(normalize(n) for n in r.pipeline_found)
            caught = pipe_set - ner_set
            if caught:
                fallback.append((r.case_id, caught))

        if fallback:
            print(f"\nRxNorm fallback recovered ({len(fallback)} cases):")
            for case_id, caught in fallback:
                print(f"  {case_id}: {caught}")

    # === Write results JSON ===

    output_path = Path(__file__).parent / "results.json"
    output = {
        "model": ner_model.MODEL_ID,
        "dataset": DATASET_PATH.name,
        "total_cases": len(results),
        "ner_precision": round(p, 4),
        "ner_recall": round(r_val, 4),
        "ner_f1": round(f1, 4),
        "avg_inference_ms": round(avg_ms, 1),
        "cases": [
            {
                "id": r.case_id,
                "category": r.category,
                "expected": r.expected,
                "ner_found": r.ner_found,
                "ner_tp": r.ner_tp,
                "ner_fp": r.ner_fp,
                "ner_fn": r.ner_fn,
            }
            for r in results
        ],
    }
    output_path.write_text(json.dumps(output, indent=2))
    print(f"\nDetailed results written to {output_path}")


if __name__ == "__main__":
    main()
